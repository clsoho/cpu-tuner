export const useI18n = create<{
  lang: Lang
  t: (key: string, vars?: Record<string, string | number>) => string
  toggleLang: () => void
  setLang: (l: Lang) => void
}>((set, get) => ({
  lang: (localStorage.getItem('cpu-tuner-lang') as Lang) || 'zh',
  t: (key: string, vars?: Record<string, string | number>) => {
    const dict = get().lang === 'zh' ? zh : en
    let val = dict[key] || key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        val = val.replace(`{${k}}`, String(v))
      }
    }
    return val
  },
  toggleLang: () => {
    const next = get().lang === 'zh' ? 'en' : 'zh'
    localStorage.setItem('cpu-tuner-lang', next)
    set({ lang: next })
  },
  setLang: (l) => {
    localStorage.setItem('cpu-tuner-lang', l)
    set({ lang: l })
  },
}))
